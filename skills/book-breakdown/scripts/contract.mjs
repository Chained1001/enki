export function tableSkeleton(name, columns, rows = []) {
  const head = `| ${columns.join(' | ')} |\n| ${columns.map(() => '---').join(' | ')} |\n`
  const body = rows.map((r) => `| ${r.join(' | ')} |\n`).join('')
  return `# ${name}\n\n${SKELETON_NOTE}\n\n${head}${body}`
}

